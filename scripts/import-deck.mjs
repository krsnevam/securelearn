// Builds app/js/deck-data.js from the program deck in deck/ (deck.json plus
// one slides/<id>.html per slide, as exported from the Slides artifact).
// Each slide keeps its 1920×1080 inline-styled markup; its <aside> speaker
// notes are split out as plain text. The markup is checked against the
// slide format's closed tag list and rejected if it carries anything that
// could run (scripts, event handlers, URLs), because the app sets it as HTML.
import { readFileSync, writeFileSync } from 'node:fs';

const ID = /^[A-Za-z0-9_-]{1,64}$/;
const TAGS = new Set(['section', 'div', 'p', 'h1', 'h2', 'h3', 'ul', 'ol', 'li', 'b', 'i', 'u', 'span', 'br', 'table', 'tr', 'th', 'td', 'x-icon', 'x-shape', 'aside']);
const deck = JSON.parse(readFileSync('deck/deck.json', 'utf8'));
const text = s => s.replace(/<[^>]+>/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, '\'').replace(/\s+/g, ' ').trim();

const slides = {};
for (const id of deck.order) {
  if (!ID.test(id)) throw new Error('bad slide id: ' + id);
  const src = readFileSync('deck/slides/' + id + '.html', 'utf8').trim();
  for (const [, tag] of src.matchAll(/<\/?([a-zA-Z][a-zA-Z0-9-]*)/g)) if (!TAGS.has(tag.toLowerCase())) throw new Error(id + ': tag <' + tag + '> is not allowed');
  if (/\son[a-z]+\s*=|javascript:|\b(src|href|srcset|action)\s*=|url\s*\(|@import|<!--/i.test(src)) throw new Error(id + ': markup that could load or run something');
  const notes = (src.match(/<aside>([\s\S]*?)<\/aside>/) || [])[1] || '';
  const html = src.replace(/<aside>[\s\S]*?<\/aside>/, '').replace(/\n/g, '');
  const head = (html.match(/<h[12][^>]*>([\s\S]*?)<\/h[12]>/) || html.match(/<p[^>]*>([\s\S]*?)<\/p>/) || [])[1] || id;
  slides[id] = { t: text(head), html, notes: text(notes) };
}
const sections = Object.values(deck.sections).map(s => ({ start: s.start, d: s.description }));
const out = '\'use strict\';\n/* The program deck, generated by scripts/import-deck.mjs from deck/. Do not edit by hand. */\n'
  + 'const DECK = ' + JSON.stringify({ title: deck.title, order: deck.order, sections, slides }) + ';\n';
writeFileSync('app/js/deck-data.js', out);
console.log('deck: ' + deck.order.length + ' slides, ' + sections.length + ' sections → app/js/deck-data.js (' + Math.round(out.length / 1024) + ' KB)');
